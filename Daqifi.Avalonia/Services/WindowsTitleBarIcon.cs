using System;
using System.Collections.Generic;
using System.IO;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using Avalonia.Controls;
using Avalonia.Interactivity;
using Avalonia.Platform;

namespace Daqifi.Avalonia.Services;

/// <summary>
/// Gives every window's title bar the small traces glyph, while the taskbar and Alt+Tab keep the
/// full app icon (#492).
/// </summary>
/// <remarks>
/// <para>
/// Windows keeps two icons per window: <c>ICON_SMALL</c> for the title bar and <c>ICON_BIG</c> for
/// the taskbar. Avalonia's <see cref="Window.Icon"/> sets both from one image, and windows that set
/// no icon get Avalonia's default, built from the exe's <c>ApplicationIcon</c>. So every title bar
/// showed the launcher icon's 16px frame: a white tile with the traces over the colour wave, which
/// reads as a smudge on the dark title bar. Picking different frames out of one .ico is not dependable either,
/// because title-bar and taskbar sizes overlap at 125-150% scaling.
/// </para>
/// <para>
/// So this sends <c>WM_SETICON ICON_SMALL</c> itself, with the frame of <c>AppIconSmall.ico</c>
/// that matches the window's DPI. Avalonia sets its own icon at two points, and each is followed
/// by an event this answers: during show, followed by <see cref="TopLevel.Opened"/>, and on
/// <c>WM_DPICHANGED</c>, followed by <see cref="TopLevel.ScalingChanged"/>.
/// <c>ICON_BIG</c> is left alone. The .ico is generated by daqifi-design-tokens'
/// <c>assets/app-icons/src/generate.py</c> (<c>daqifi-small.ico</c>); regenerate it there, never
/// edit it here.
/// </para>
/// <para>
/// Avalonia answers <c>WM_GETICON</c> from its own icon, so asking a window for its small icon
/// returns the launcher icon's handle even though the title bar draws the glyph. Check this by
/// looking at the title bar, not by reading the handle back.
/// </para>
/// <para>
/// Windows only. macOS draws no per-window icon, and Linux window managers take one icon set
/// from <see cref="Window.Icon"/>.
/// </para>
/// </remarks>
internal static class WindowsTitleBarIcon
{
    private const string ICON_URI = "avares://Daqifi.Avalonia/Daqifi.Desktop/Images/AppIconSmall.ico";

    /// <summary>The icon this class created for each window it has hooked.</summary>
    private static readonly ConditionalWeakTable<Window, IconHandle> Icons = new();

    private static IReadOnlyList<IcoFrame>? _frames;

    /// <summary>
    /// Registers the title-bar icon for every window the app opens from now on. A no-op off Windows.
    /// </summary>
    public static void Install()
    {
        if (!OperatingSystem.IsWindows()) { return; }

        try
        {
            using var stream = AssetLoader.Open(new Uri(ICON_URI));
            using var buffer = new MemoryStream();
            stream.CopyTo(buffer);
            _frames = IcoFrames.Parse(buffer.ToArray());
        }
        catch (Exception ex) when (ex is IOException or InvalidDataException)
        {
            // Cosmetic: windows keep the launcher icon rather than the app failing to start.
            // A shipped .ico that fails here is caught by WindowsTitleBarIconTests.
            System.Diagnostics.Debug.WriteLine($"Title-bar icon not installed: {ex.Message}");
            return;
        }

        Window.WindowOpenedEvent.AddClassHandler<Window>(OnWindowShowing);
    }

    /// <remarks>
    /// Despite its name, <see cref="Window.WindowOpenedEvent"/> fires at the start of showing, before
    /// the window has its icon, so it is only where to hook: an icon set here would be replaced by
    /// Avalonia's default. It fires again if a hidden window is shown again, hence the guard.
    /// </remarks>
    private static void OnWindowShowing(Window window, RoutedEventArgs e)
    {
        if (!Icons.TryAdd(window, new IconHandle())) { return; }

        window.Opened += (_, _) => Apply(window);
        window.ScalingChanged += (_, _) => Apply(window);
        window.Closed += (_, _) => { if (Icons.TryGetValue(window, out var icon)) { icon.Replace(IntPtr.Zero); } };
    }

    private static void Apply(Window window)
    {
        if (_frames is null || _frames.Count == 0) { return; }
        var handle = window.TryGetPlatformHandle();
        if (handle is null || handle.HandleDescriptor != "HWND") { return; }

        var dpi = (uint)Math.Round(96 * window.RenderScaling);
        var px = NativeMethods.GetSystemMetricsForDpi(NativeMethods.SM_CXSMICON, dpi);
        if (px <= 0) { px = (int)Math.Round(16 * window.RenderScaling); }

        var frame = IcoFrames.Pick(_frames, px);
        var hIcon = NativeMethods.CreateIconFromResourceEx(
            frame.Data, (uint)frame.Data.Length, true, 0x00030000, px, px, 0);
        if (hIcon == IntPtr.Zero) { return; }

        NativeMethods.SendMessage(handle.Handle, NativeMethods.WM_SETICON, (IntPtr)NativeMethods.ICON_SMALL, hIcon);

        // Only icons this class made are destroyed; the handle WM_SETICON returns may be Avalonia's.
        if (Icons.TryGetValue(window, out var icon)) { icon.Replace(hIcon); }
    }

    /// <summary>Owns one window's icon, which must outlive its use by the title bar.</summary>
    private sealed class IconHandle
    {
        private IntPtr _handle;

        public void Replace(IntPtr handle)
        {
            if (_handle != IntPtr.Zero && OperatingSystem.IsWindows())
            {
                NativeMethods.DestroyIcon(_handle);
            }
            _handle = handle;
        }
    }

    private static class NativeMethods
    {
        public const int WM_SETICON = 0x0080;
        public const int ICON_SMALL = 0;
        public const int SM_CXSMICON = 49;

        [DllImport("user32.dll")]
        public static extern int GetSystemMetricsForDpi(int nIndex, uint dpi);

        [DllImport("user32.dll", SetLastError = true)]
        public static extern IntPtr CreateIconFromResourceEx(
            byte[] presbits, uint dwResSize, bool fIcon, uint dwVer, int cxDesired, int cyDesired, uint flags);

        [DllImport("user32.dll", SetLastError = true)]
        public static extern bool DestroyIcon(IntPtr hIcon);

        [DllImport("user32.dll")]
        public static extern IntPtr SendMessage(IntPtr hWnd, int msg, IntPtr wParam, IntPtr lParam);
    }
}

/// <summary>One image inside an .ico file: its pixel size and its encoded bytes (PNG or DIB).</summary>
internal sealed record IcoFrame(int Size, byte[] Data);

/// <summary>Reads the frames out of an .ico file and picks one for a target size.</summary>
internal static class IcoFrames
{
    /// <summary>
    /// Parses an .ico container into its frames. Throws <see cref="InvalidDataException"/> when the
    /// header or an entry does not fit inside <paramref name="ico"/>.
    /// </summary>
    public static IReadOnlyList<IcoFrame> Parse(byte[] ico)
    {
        if (ico.Length < 6 || BitConverter.ToUInt16(ico, 0) != 0 || BitConverter.ToUInt16(ico, 2) != 1)
        {
            throw new InvalidDataException("Not an .ico file.");
        }

        var count = BitConverter.ToUInt16(ico, 4);
        if (ico.Length < 6 + 16 * count) { throw new InvalidDataException("Truncated .ico directory."); }

        var frames = new List<IcoFrame>(count);
        for (var i = 0; i < count; i++)
        {
            var entry = 6 + 16 * i;
            var size = ico[entry] == 0 ? 256 : ico[entry];
            var length = BitConverter.ToUInt32(ico, entry + 8);
            var offset = BitConverter.ToUInt32(ico, entry + 12);
            if ((ulong)offset + length > (ulong)ico.Length)
            {
                throw new InvalidDataException($"Frame {i} runs past the end of the .ico.");
            }

            var data = new byte[length];
            Array.Copy(ico, offset, data, 0, length);
            frames.Add(new IcoFrame(size, data));
        }

        return frames;
    }

    /// <summary>
    /// The smallest frame at least <paramref name="px"/> wide, so Windows only ever scales down;
    /// the largest frame when none is big enough.
    /// </summary>
    public static IcoFrame Pick(IReadOnlyList<IcoFrame> frames, int px)
    {
        IcoFrame? best = null;
        IcoFrame? largest = null;
        foreach (var frame in frames)
        {
            if (largest is null || frame.Size > largest.Size) { largest = frame; }
            if (frame.Size >= px && (best is null || frame.Size < best.Size)) { best = frame; }
        }

        return best ?? largest ?? throw new ArgumentException("No frames.", nameof(frames));
    }
}
